# ================================================================ 噪声
def add_noise(rng: random.Random, text: str, sentiment: str) -> str:
    """模拟真实输入的脏数据：错别字、缺标点、重复标点、换行。

    注意：表情符号必须和情感一致，否则等于给标签注入噪声
    （正面句子配 😡 会让模型学到错误信号）。
    """
    emoji = {"负面": " 😡", "正面": " 🙂", "中性": ""}.get(sentiment, "")
    ops = [
        lambda t: t,
        lambda t: t,
        lambda t: t + "。。",
        lambda t: t.replace("的", "得") if "的" in t else t,
        lambda t: t.replace("在吗", "再吗") if "在吗" in t else t,
        lambda t: t + "\n" + "麻烦回一下",
        lambda t: t.replace("退", "推") if "退" in t and rng.random() < 0.3 else t,
        lambda t: t + emoji if emoji and rng.random() < 0.5 else t,
        lambda t: "    " + t + "  ",
    ]
    return ops[rng.randrange(len(ops))](text)


def compose(rng: random.Random, intent: str,
            body_split: dict | None = None, split: str | None = None) -> tuple[str, str]:
    pool = BODIES[intent]
    if body_split is not None:
        allowed = [b for b in pool if body_split[intent].get(b) == split]
        if allowed:
            pool = allowed
    body, sent = rng.choice(pool)

    # 开场：按情感选语气池，但允许错配（这样"礼貌+投诉"会自然出现）
    if rng.random() < 0.25:
        opener_pool = OPENERS[rng.choice(["polite", "casual", "angry"])]
    else:
        key = {"负面": "angry", "正面": "polite", "中性": "polite"}[sent]
        opener_pool = OPENERS[key] + OPENERS["none"]
    opener = rng.choice(opener_pool)

    closer = rng.choice(CLOSERS[sent]) if rng.random() < 0.6 else ""
    text = f"{opener}{body}{('，' + closer) if closer else ''}"
    return text, sent


def make_session(rng: random.Random, idx: int,
                 body_split: dict | None = None, split: str | None = None) -> Session:
    intent = INTENT_NAMES[rng.randrange(len(INTENT_NAMES))]
    first_text, first_sent = compose(rng, intent, body_split, split)

    msgs: list[Message] = []
    sid = f"S{idx:04d}"
    turn = 0

    def cust(text, it, st):
        if rng.random() < 0.35:
            text = add_noise(rng, text, st)
        return Message(sid, turn, "customer", text, it, st)

    msgs.append(cust(first_text, intent, first_sent))
    turn += 1

    for _ in range(rng.choice([0, 1, 1, 2, 2, 3])):
        msgs.append(Message(sid, turn, "agent", rng.choice(AGENT_REPLIES[intent])))
        turn += 1

        if rng.random() < 0.55:
            fol_intent = intent
        else:
            fol_intent = INTENT_NAMES[rng.randrange(len(INTENT_NAMES))]
        text, sent = compose(rng, fol_intent, body_split, split)

        # 客户情绪有惯性：上一句负面，更容易继续负面
        if first_sent == "负面" and sent == "中性" and rng.random() < 0.35:
            sent = "负面"
        msgs.append(cust(text, fol_intent, sent))
        turn += 1

    if rng.random() < 0.5:
        msgs.append(Message(sid, turn, "agent", rng.choice(FOLLOWUP)))

    return Session(sid, "text", msgs)


