"""中文程度副词归一化：把"好/特/超"等口语程度副词改写成标准写法。

为什么需要这一层（而不是继续加训练数据）：
  用户反馈"客服态度好差"被判成正面，置信度 0.97。
  连续两轮补数据都没根治 —— 因为中文里"好"同时是形容词（good）和
  程度副词（very），模型在短句里会优先抓"好"的正面语义。
  "好差"这种**单字歧义 + 否定性形容词**的组合，靠数据规模硬堆性价比很低：
  可能出现的搭配是开放集合（好差/好烂/好慢/好贵/好难…），
  测试集永远会漏。

  所以这里用一条确定性的规则兜底：
    把"好/特/超/贼/巨 + 负面形容词"改写成"很 + 负面形容词"，
    让模型只需要理解"很+形容词"这一种它已经学会的结构。
  这是**规则 + 模型**的结合，在工业 NLP 里很常见（终端的规范化层）。

设计原则：
  - 只在**后面紧跟明确的负面形容词**时才改写，不做全局替换
    （"服务态度好" 不能被改）
  - 规则可关闭，方便做消融对比（--no-normalize）
"""

from __future__ import annotations

import re

# 明确的负面形容词（只在词表内改写，避免误伤"好"的正常用法）
NEG_ADJ = (
    "差|烂|慢|贵|难用|难吃|难看|难听|糟|惨|坑|烦|气人|无语|敷衍|冷漠|凶|"
    "失望|后悔|恶心|难受|麻烦|久了|久"
)

# 口语程度副词，等价于"很/非常"
INTENSIFIERS = "好|特|超|贼|巨|特别"

# "好差" -> "很差"；"特差" -> "很差"
_PATTERN = re.compile(rf"({INTENSIFIERS})({NEG_ADJ})")

# 需要保护的正向搭配：这些"好+词"里的"好"是形容词，不是程度副词
_PROTECT = [
    re.compile(p)
    for p in (
        r"好(评|用|看|听|吃|玩|住|心|处|事|了|的|么|呀|啊)",
        r"态度好(?![差烂慢贵])",
        r"质量好(?!差)",
        r"服务好(?!差|烂)",
        r"好好",
    )
]


def normalize(text: str) -> str:
    """把口语程度副词改写成'很'，使模型只需理解标准结构。

    >>> normalize("客服态度好差")
    '客服态度很差'
    >>> normalize("服务态度好")
    '服务态度好'          # 正向用法不动
    """
    t = str(text)

    # 先记下受保护片段的占位，避免被改写
    protected: list[str] = []

    def _shield(m: re.Match) -> str:
        protected.append(m.group(0))
        return f"\x00{len(protected) - 1}\x00"

    for rx in _PROTECT:
        t = rx.sub(_shield, t)

    # 改写程度副词 + 负面形容词
    t = _PATTERN.sub(lambda m: "很" + m.group(2), t)

    # 还原占位
    def _restore(m: re.Match) -> str:
        return protected[int(m.group(1))]

    t = re.sub(r"\x00(\d+)\x00", _restore, t)
    return t


if __name__ == "__main__":
    cases = [
        "客服态度好差", "客服态度好烂", "质量好差", "服务态度好差",
        "这个价格好贵", "包装好差", "东西好难用", "态度真的好差",
        "服务态度好，很满意", "质量好，用着很舒服", "好好用啊",
        "客服态度很好，感谢", "这个东西特差劲", "超级烂的服务",
    ]
    for c in cases:
        print(f"  {c:18s} -> {normalize(c)}")